// Builds the player version into dist/: the game without dev-only pods, a static pod list (no server needed),
// a service worker so it works offline and installs as an app, and preload hints so modules load in parallel.
// Usage: node tools/build-web.js   → dist/ (serve it from any static host; the Android app packages it too)
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..'), SRC = path.join(ROOT, 'game'), OUT = path.join(ROOT, 'dist');
const SKIP_DIRS = new Set(['legacy', 'dev']);
const DEV_PODS = new Set(['bots', 'reaction-form']); // playtest tools; players never see them

fs.rmSync(OUT, { recursive: true, force: true });
const files = [];
function copy(dir, rel = '') {
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${d.name}` : d.name;
    if (d.isDirectory()) {
      if (SKIP_DIRS.has(d.name) && !rel) continue;
      if (rel === 'pods' && DEV_PODS.has(d.name)) continue;
      copy(path.join(dir, d.name), r);
    } else {
      fs.mkdirSync(path.join(OUT, rel), { recursive: true });
      fs.copyFileSync(path.join(dir, d.name), path.join(OUT, r));
      files.push(r);
    }
  }
}
copy(SRC);

const pods = fs.readdirSync(path.join(OUT, 'pods')).filter(n => fs.existsSync(path.join(OUT, 'pods', n, 'pod.js'))).sort();
fs.writeFileSync(path.join(OUT, 'pods.json'), JSON.stringify(pods));
files.push('pods.json');

// The cache version changes whenever any shipped file does, so players get updates on their next visit.
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(OUT, f)));
const version = hash.digest('hex').slice(0, 12);

const js = files.filter(f => f.endsWith('.js'));
let html = fs.readFileSync(path.join(OUT, 'index.html'), 'utf8');
const preload = js.map(f => `<link rel="modulepreload" href="${f}">`).join('\n');
// Not inside the Android app: it already has every file locally, and a cache there would outlive app updates.
const register = `<script>if ('serviceWorker' in navigator && location.protocol.startsWith('http') && !window.Capacitor) navigator.serviceWorker.register('sw.js');</script>`;
html = html.replace('</head>', `${preload}\n${register}\n</head>`);
fs.writeFileSync(path.join(OUT, 'index.html'), html);

fs.writeFileSync(path.join(OUT, 'sw.js'), `// Generated by tools/build-web.js. The whole game is precached, so it runs offline.
// Cache-first for everything, so a page and its modules always come from the same version; a new version is
// fetched in the background and takes over on the next launch.
const CACHE = 'lure-${version}', FILES = ${JSON.stringify(['./', ...files])};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES))); self.skipWaiting(); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(r => r || fetch(e.request)));
});
`);
console.log(`dist/: ${files.length + 1} files, ${pods.length} pods, version ${version}`);
