// Writes leaderboard-worker/src/sim-pods.generated.js: an import of every pod's sim.js (game/pods/*/sim.js), in name
// order, the same order the game loads its pods. The Worker bundles it to replay runs (leaderboard-worker/src/
// replay-sim.js), so deleting a pod folder takes it out of the Worker's simulation too, just as from the game.
// Run by wrangler before every build and dev start (wrangler.toml [build]) and by npm test; the file isn't committed.
// Usage: node tools/list-sim-pods.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), PODS = path.join(ROOT, 'game', 'pods');
const OUT = path.join(ROOT, 'leaderboard-worker', 'src', 'sim-pods.generated.js');

const names = fs.readdirSync(PODS).filter(n => fs.existsSync(path.join(PODS, n, 'sim.js'))).sort();
const lines = [
  '// Generated by tools/list-sim-pods.js: every pod\'s simulation, in the order the game loads pods. Do not edit.',
  ...names.map(n => `import '../../game/pods/${n}/sim.js';`),
  `export const SIM_PODS = ${JSON.stringify(names)};`,
  '',
];
const text = lines.join('\n');
if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) fs.writeFileSync(OUT, text);
console.log(`sim pods: ${names.join(', ')}`);
